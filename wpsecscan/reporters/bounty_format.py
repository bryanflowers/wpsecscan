# #51 — pentest engagement letter
ENGAGEMENT_LETTER = """# Penetration Test Engagement Letter

**Between**: {vendor}
**And**: {client}
**Date**: {date}

## 1. Scope

The engagement covers automated + manual security testing of the following
assets, all owned by or operated on behalf of {client}:

- {targets}

The following are explicitly EXCLUDED from scope:
- Production payment systems handling live PCI data (unless separately scoped)
- DoS / DDoS testing
- Social-engineering / phishing of {client} staff
- Physical-security testing

## 2. Authorisation

{client} hereby authorises {vendor} to conduct security testing within the
scope above, using techniques up to and including:
- Reconnaissance (passive + active)
- Vulnerability scanning (automated + manual)
- Exploitation attempts on findings, proportionate to confirmation needs
- Post-exploitation enumeration sufficient to demonstrate impact

{vendor} shall not:
- Exfiltrate live customer data beyond what is needed to demonstrate finding
- Persist access after the engagement window
- Disclose findings to third parties before {client} agrees release

## 3. Deliverables

- Executive summary report (PDF) — within 5 business days of engagement end
- Technical findings report (HTML + JSON) — same day
- Re-test of remediated items — up to 30 days post-delivery

## 4. Engagement window

Start: {start_date}
End:   {end_date}

## 5. Communications

Primary contact ({vendor}): _____________________
Primary contact ({client}): _____________________
Emergency escalation:        _____________________

## 6. Liability

{vendor} carries professional liability insurance in the amount of
$___________. {client} acknowledges that defensive security testing
involves manipulation of production systems and that unanticipated
service disruption is a known risk.

---

Signed:

{vendor}: ________________________   Date: ________

{client}: ________________________   Date: ________
"""


def engagement_letter(*, vendor: str, client: str, targets: list[str],
                       date: str, start_date: str, end_date: str) -> str:
    return ENGAGEMENT_LETTER.format(
        vendor=vendor, client=client,
        targets="\n- ".join(targets),
        date=date, start_date=start_date, end_date=end_date,
    )
