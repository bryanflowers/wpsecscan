HACKERONE_TEMPLATE = """**Summary**: {title}

**Severity**: {severity}

**URL**: {url}

**Steps to reproduce**:
{evidence}

**Impact**:
This vulnerability allows {impact_summary}.

**Remediation**:
{remediation}

**Tags**: {tags}

---
*Submission generated by WPSecScan.*
"""

BUGCROWD_TEMPLATE = """## Vulnerability: {title}

**VRT**: {vrt}
**CVSS**: {cvss}
**URL**: {url}

### Description
{evidence}

### Proof of Concept
```
{poc}
```

### Mitigation
{remediation}
"""


def _safe(value: str) -> str:
    """Escape `{` / `}` so str.format() doesn't re-interpolate user content."""
    if value is None:
        return ""
    return str(value).replace("{", "{{").replace("}", "}}")


def format_for_hackerone(finding, *, check_id: str = "") -> str:
    sev = (finding.severity or "info").upper()
    return HACKERONE_TEMPLATE.format(
        title=_safe(finding.title),
        severity=sev,
        url=_safe(finding.url) or "(not specified)",
        evidence=_safe(finding.evidence) or "(not specified)",
        impact_summary={"critical": "remote code execution / full account takeover",
                         "high": "significant data exposure or privilege escalation",
                         "medium": "limited data exposure or denial-of-service",
                         "low": "minor information disclosure",
                         "info": "non-exploitable but suboptimal configuration"}.get(finding.severity, "?"),
        remediation=_safe(finding.remediation) or "See report.",
        tags=f"#wpsecscan #{check_id}" if check_id else "#wpsecscan",
    )


def format_for_bugcrowd(finding, *, check_id: str = "") -> str:
    return BUGCROWD_TEMPLATE.format(
        title=_safe(finding.title),
        vrt="see https://bugcrowd.com/vulnerability-rating-taxonomy",
        cvss="(compute manually)",
        url=_safe(finding.url) or "(not specified)",
        evidence=_safe(finding.evidence) or "(not specified)",
        poc=_safe(finding.evidence[:1000]) if finding.evidence else "(not specified)",
        remediation=_safe(finding.remediation) or "See report.",
    )


