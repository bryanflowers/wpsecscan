def siem_forward(report: Any, *, endpoint: str, kind: str = "splunk-hec",
                  token: str = "") -> dict:
    """Forward findings to a SIEM. kind ∈ {splunk-hec, elastic, loki, generic}."""
    if os.environ.get("WPSECSCAN_NO_NETWORK"):
        return {"ok": False, "error": "WPSECSCAN_NO_NETWORK"}
    d = report.to_dict() if hasattr(report, "to_dict") else (report or {})
    target = d.get("target", "")
    events: list[dict] = []
    for r in d.get("results", []) or []:
        cid = r.get("check_id", "?")
        for f in r.get("findings", []) or []:
            events.append({
                "ts": int(time.time()),
                "source": "wpsecscan",
                "target": target,
                "check_id": cid,
                "severity": f.get("severity"),
                "title": f.get("title"),
                "url": f.get("url"),
            })

    if kind == "splunk-hec":
        body = "\n".join(json.dumps({"event": e}) for e in events)
        headers = {"Authorization": f"Splunk {token}"} if token else {}
    elif kind == "elastic":
        lines = []
        for e in events:
            lines.append(json.dumps({"index": {"_index": "wpsecscan"}}))
            lines.append(json.dumps(e))
        body = "\n".join(lines) + "\n"
        headers = {"Content-Type": "application/x-ndjson"}
        if token:
            headers["Authorization"] = f"ApiKey {token}"
    elif kind == "loki":
        body = json.dumps({"streams": [{"stream": {"app": "wpsecscan"},
                                            "values": [[str(int(time.time() * 1e9)), json.dumps(e)]
                                                       for e in events]}]})
        headers = {"Content-Type": "application/json"}
        if token:
            headers["Authorization"] = f"Bearer {token}"
    else:
        body = "\n".join(json.dumps(e) for e in events)
        headers = {"Content-Type": "application/x-ndjson"}
        if token:
            headers["Authorization"] = f"Bearer {token}"

    req = urllib.request.Request(endpoint, data=body.encode("utf-8"),
                                   method="POST",
                                   headers={"User-Agent": "WPSecScan/siem_forward",
                                              **headers})
    try:
        with urllib.request.urlopen(req, timeout=20) as r:
            return {"ok": r.status < 300, "status": r.status, "events": len(events)}
    except (HTTPError, URLError, OSError) as e:
        return {"ok": False, "error": str(e), "events": len(events)}


