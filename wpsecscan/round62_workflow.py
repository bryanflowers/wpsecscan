# ---- #E70 auto-resume marker ----

def _home() -> Path:
    return Path(os.environ.get("WPSECSCAN_HOME") or (Path.home() / ".wpsecscan"))


def write_resume_marker(target: str, completed_check_ids: list[str]) -> None:
    p = _home() / "resume_marker.json"
    try:
        p.parent.mkdir(parents=True, exist_ok=True)
        if p.is_symlink():
            p.unlink()
        p.write_text(json.dumps({"target": target,
                                    "completed": completed_check_ids,
                                    "ts": int(time.time())}), encoding="utf-8")
    except OSError:
        pass


def load_resume_marker() -> dict | None:
    p = _home() / "resume_marker.json"
    if not p.exists() or p.is_symlink():
        return None
    try:
        d = json.loads(p.read_text(encoding="utf-8"))
        return d if isinstance(d, dict) else None
    except (OSError, json.JSONDecodeError):
        return None


def clear_resume_marker() -> None:
    p = _home() / "resume_marker.json"
    if p.exists() and not p.is_symlink():
        try:
            p.unlink()
        except OSError:
            pass


