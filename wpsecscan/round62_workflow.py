# ---- #E61 daily digest ----

def render_daily_digest(sites: list[dict]) -> str:
    """Daily summary — only sites with NEW critical/high in the last 24h."""
    cutoff = int(time.time()) - 86400
    lines = ["WPSecScan daily digest", "=" * 40, ""]
    any_new = False
    for s in sites or []:
        ts = int(s.get("last_scan_ts") or 0)
        if ts < cutoff:
            continue
        c = int(s.get("last_critical") or 0)
        h = int(s.get("last_high") or 0)
        if c == 0 and h == 0:
            continue
        any_new = True
        lines.append(f"  {s.get('url', '?')}")
        lines.append(f"    NEW critical={c} high={h}  "
                       f"(scanned {time.strftime('%H:%M', time.localtime(ts))})")
    if not any_new:
        lines.append("  No new critical/high findings in the last 24h.")
    return "\n".join(lines)


# ---- #E62 PR comment body ----

def pr_comment_body(report: Any, *, baseline_critical: int = 0,
                      baseline_high: int = 0) -> str:
    d = report.to_dict() if hasattr(report, "to_dict") else (report or {})
    s = d.get("summary", {})
    cur_crit, cur_high = int(s.get("critical", 0)), int(s.get("high", 0))
    delta_crit = cur_crit - baseline_critical
    delta_high = cur_high - baseline_high
    icon = "[OK]" if delta_crit <= 0 and delta_high <= 0 else "[WARN]"
    return (
        f"## {icon} WPSecScan - {d.get('target', '?')}\n\n"
        f"| Severity | Count | Delta vs baseline |\n"
        f"|---|---|---|\n"
        f"| Critical | {cur_crit} | {'+' if delta_crit > 0 else ''}{delta_crit} |\n"
        f"| High | {cur_high} | {'+' if delta_high > 0 else ''}{delta_high} |\n"
        f"| Medium | {s.get('medium', 0)} | - |\n"
        f"| Low | {s.get('low', 0)} | - |\n\n"
        f"Risk score: **{d.get('risk_score', 0)}/100**\n\n"
        f"_Generated by [WPSecScan](https://github.com/bryanflowers/wpsecscan)._"
    )


# ---- #E63 pre-commit hook ----

def pre_commit_hook_script() -> str:
    return r"""#!/bin/sh
# WPSecScan pre-commit hook
# Install: cp this to .git/hooks/pre-commit && chmod +x .git/hooks/pre-commit
set -e
STAGED=$(git diff --cached --name-only --diff-filter=ACM | grep -E "\.(php|js)$" || true)
[ -z "$STAGED" ] && exit 0
FAIL=0
for f in $STAGED; do
  case "$f" in
    *wp-content/plugins/*|*wp-content/themes/*) ;;
    *) continue ;;
  esac
  if grep -nE "(passthru|system|shell_exec|popen|exec)\s*\(\s*\\\$_" "$f" >/dev/null 2>&1; then
    echo "BLOCKED: $f has shell-exec on \$_GET/POST/REQUEST input."
    FAIL=1
  fi
  if grep -nE "(eval|assert)\s*\(\s*\\\$_" "$f" >/dev/null 2>&1; then
    echo "BLOCKED: $f has eval() on user input."
    FAIL=1
  fi
done
[ $FAIL -ne 0 ] && { echo "Bypass with --no-verify (NOT RECOMMENDED)"; exit 1; }
exit 0
"""


# ---- #E64 watch mode ----

def watch_directory(path: str, *, on_change, debounce_s: float = 1.0) -> None:
    """Block + call `on_change(changed_path)` when files modified."""
    try:
        from watchdog.observers import Observer
        from watchdog.events import FileSystemEventHandler
    except ImportError:
        print("Watch mode needs: pip install watchdog", file=sys.stderr)
        return
    last_fired: dict[str, float] = {}

    class _H(FileSystemEventHandler):
        def on_any_event(self, event) -> None:
            if event.is_directory:
                return
            now = time.monotonic()
            if now - last_fired.get(event.src_path, 0) < debounce_s:
                return
            last_fired[event.src_path] = now
            try:
                on_change(event.src_path)
            except Exception as e:  # noqa: BLE001
                print(f"watch handler error: {e}", file=sys.stderr)

    obs = Observer()
    obs.schedule(_H(), path, recursive=True)
    obs.start()
    try:
        while True:
            time.sleep(0.5)
    except KeyboardInterrupt:
        obs.stop()
    obs.join()


# ---- #E65 companion log tail ----

def companion_log_tail(target_url: str, *, companion_token: str,
                        last_n: int = 50) -> list[dict]:
    if os.environ.get("WPSECSCAN_NO_NETWORK"):
        return []
    from urllib.parse import urlparse
    parsed = urlparse(target_url)
    base = f"{parsed.scheme}://{parsed.netloc}"
    req = urllib.request.Request(
        f"{base}/wp-json/wpsecscan/v1/activity-log?n={int(last_n)}",
        headers={"X-WPSecScan-Token": companion_token,
                  "User-Agent": "WPSecScan/companion-log-tail"},
    )
    try:
        with urllib.request.urlopen(req, timeout=15) as r:
            if r.status != 200:
                return []
            data = json.loads(r.read().decode("utf-8", errors="replace"))
        return data if isinstance(data, list) else []
    except (HTTPError, URLError, OSError, ValueError):
        return []


